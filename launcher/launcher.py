    def log_to_terminal(self, text):
        clean_text = text.strip("\r\n")
        if not clean_text:
            return

        debug_enabled = getattr(self, "debug_logs_var", None) is not None and self.debug_logs_var.get()

        if should_hide_log_line(clean_text, debug_enabled=debug_enabled):
            return

        is_progress = clean_text.startswith("⏱ Loop") or clean_text.startswith("Loop")

        if getattr(self, "last_line_is_progress", False) and is_progress:
            self.terminal.delete("end-2c linestart", "end-1c")
            self.terminal.insert("end", clean_text + "\n")
        else:
            self.terminal.insert("end", clean_text + "\n")

        self.last_line_is_progress = is_progress
        self.terminal.see("end")

    def read_process_output(self, process):
        for line in iter(process.stdout.readline, ''):
            if line:
                self.terminal.after(0, self.log_to_terminal, line)
        process.stdout.close()

