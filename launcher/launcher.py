    def discover_wsl_cameras(self):
        """Discover usable V4L2 camera capture nodes inside WSL.

        Delegates OpenCV/V4L2 probing to tools/discover_wsl_cameras.py and
        converts its CAMERA lines into launcher camera config dictionaries.
        """
        camera_names = ["wrist", "workspace", "side", "overhead"]
        script_path = LAUNCHER_DIR / "discover_wsl_cameras.py"
        wsl_script_path = str(script_path).replace("\\", "/").replace("C:", "/mnt/c").replace("c:", "/mnt/c")

        try:
            res = subprocess.run(
                [
                    "wsl",
                    "--",
                    "bash",
                    "-lc",
                    f"source {WSL_VENV_PATH}/bin/activate && PY_SITE=$(python3 -c 'import site; print(site.getsitepackages()[0])') && export LD_LIBRARY_PATH=$PY_SITE/cmeel.prefix/lib:$LD_LIBRARY_PATH && python3 '{wsl_script_path}'",
                ],
                capture_output=True,
                text=True,
                timeout=35,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )
        except Exception as e:
            self.log_to_terminal(f"⚠️ Camera discovery failed: {e}\n")
            return []

        cameras = []

        for line in (res.stdout or "").splitlines():
            if line.startswith("SKIP\t"):
                parts = line.split("\t")
                if len(parts) >= 4:
                    self.log_to_terminal(f"⚠️ Skipping {parts[1]} index {parts[2]}: {parts[3]}\n")
                continue

            if not line.startswith("CAMERA\t"):
                continue

            parts = line.split("\t")
            if len(parts) < 3:
                continue

            dev = parts[1]
            index = int(parts[2])
            usb_name = parts[3].strip() if len(parts) >= 4 else ""

            if len(cameras) >= len(camera_names):
                break

            name = camera_names[len(cameras)]

            cameras.append(
                {
                    "name": name,
                    "index": index,
                    "video_index": index,
                    "device": dev,
                    "usb_name": usb_name,
                    "width": 640,
                    "height": 480,
                    "fps": 30,
                    "fourcc": "MJPG",
                    "warmup_s": 15,
                    "backend": "V4L2",
                }
            )

        if cameras:
            self.log_to_terminal("✨ OpenCV-validated camera devices detected:\n")
            for cam in cameras:
                friendly = cam.get("usb_name") or f"index {cam['index']}"
                self.log_to_terminal(
                    f"   - {cam['name']}: {friendly} | {cam['device']} → index {cam['index']} "
                    f"(MJPG 640x480@30)\n"
                )
        else:
            self.log_to_terminal("❌ No OpenCV-usable MJPG cameras found in WSL.\n")

        return cameras

    def final_validate_selected_cameras(self):
        """Final OpenCV validation immediately before launching the server.

        Physical cameras are validated by tools/validate_wsl_cameras.py.
        Mock/no-camera modes skip validation.
        """
        if self.no_cameras_var.get() or not self.detected_cameras:
            return True

        import json

        camera_specs = []
        for cam in self.detected_cameras:
            camera_specs.append(
                {
                    "name": cam.get("name", "camera"),
                    "index": self.camera_config_index(cam),
                    "width": int(cam.get("width", 640)),
                    "height": int(cam.get("height", 480)),
                    "fps": int(cam.get("fps", 30)),
                    "fourcc": cam.get("fourcc", "MJPG"),
                }
            )

        specs_path = RUNTIME_DIR / "camera_specs.json"
        specs_path.write_text(json.dumps(camera_specs), encoding="utf-8")

        script_path = LAUNCHER_DIR / "validate_wsl_cameras.py"

        wsl_specs_path = str(specs_path).replace("\\", "/").replace("C:", "/mnt/c").replace("c:", "/mnt/c")
        wsl_script_path = str(script_path).replace("\\", "/").replace("C:", "/mnt/c").replace("c:", "/mnt/c")

        try:
            res = subprocess.run(
                [
                    "wsl",
                    "--",
                    "bash",
                    "-lc",
                    f"source {WSL_VENV_PATH}/bin/activate && PY_SITE=$(python3 -c 'import site; print(site.getsitepackages()[0])') && export LD_LIBRARY_PATH=$PY_SITE/cmeel.prefix/lib:$LD_LIBRARY_PATH && python3 '{wsl_script_path}' '{wsl_specs_path}'",
                ],
                capture_output=True,
                text=True,
                timeout=25,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )
        except Exception as e:
            self.log_to_terminal(f"❌ Final camera validation failed to run: {e}\n")
            return False

        failed = []
        for line in (res.stdout or "").splitlines():
            if line.startswith("FAIL\t"):
                parts = line.split("\t")
                if len(parts) >= 3:
                    failed.append((parts[1], parts[2]))

        if res.returncode == 0 and not failed:
            return True

        if failed:
            self.log_to_terminal("❌ Camera validation failed just before launch:\n")
            for name, index in failed:
                self.log_to_terminal(f"   - {name}: OpenCV could not reopen index {index}\n")
        else:
            err = ((res.stdout or "") + "\n" + (res.stderr or "")).strip()
            self.log_to_terminal(f"❌ Camera validation failed just before launch: {err}\n")

        return False

