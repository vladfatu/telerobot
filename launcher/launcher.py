    def is_usbipd_busid(self, value):
        """Return True only for real usbipd BUSIDs like '1-4' or '2-2'.

        usbipd list may also contain persisted device GUIDs. Those are not valid
        for --busid attach and must be ignored.
        """
        return isinstance(value, str) and re.match(r"^\d+-\d+$", value.strip()) is not None

