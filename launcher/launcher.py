    def prepare_camera_role_selection(self, usbipd_out):
        """Prompt for camera roles before attaching cameras to WSL."""
        if self.no_cameras_var.get():
            return

        camera_candidates = self.build_windows_camera_candidates(usbipd_out)
        if not camera_candidates:
            return

        self.prompt_camera_assignment_before_attach(camera_candidates)
        self.last_camera_buses = [
            cam.get("busid")
            for cam in getattr(self, "pending_camera_roles", [])
            if cam.get("busid") and cam.get("role") != "disabled"
        ]

    def setup_robot_arm(self, usbipd_out):
        """Attach the robot arm to WSL and detect its serial port."""
        arm_ready = self.dummy_var.get()

        if self.dummy_var.get():
            self.log_to_terminal(">> Dummy Mode Active: Bypassing physical Arm connection.\n")
            return True

        self.log_to_terminal(">> Setting up Robot Arm...\n")

        try:
            arm_busid = None

            for line in usbipd_out.splitlines():
                if "1a86:55d3" in line or "CH34" in line:
                    parts = line.split()
                    if parts and self.is_usbipd_busid(parts[0]):
                        arm_busid = parts[0]
                        break

            if not arm_busid:
                self.log_to_terminal("⚠️ WARNING: No robot arm found via usbipd list.\n")
                return False

            self.ensure_arm_bus_shared(arm_busid)

            arm_attached_ok, attach_text = self.attach_usbipd_device_to_wsl(
                arm_busid,
                "Arm",
                attempts=3,
            )

            if not arm_attached_ok:
                short_attach_error = (attach_text.splitlines()[-1] if attach_text.splitlines() else attach_text).strip()
                self.log_to_terminal(f"⚠️ Failed to attach Arm BUSID {arm_busid}: {short_attach_error}\n")
                return False

            self.log_to_terminal(f"✨ Successfully attached Arm BUSID {arm_busid}!\n")

            port_match = self.find_wsl_serial_port()
            if not port_match:
                self.log_to_terminal("⚠️ Arm attached, but no ttyACM/ttyUSB serial port appeared.\n")
                return False

            self.detected_port = port_match
            self.log_to_terminal(f"✨ Auto-detected Arm Port: {self.detected_port}\n")
            arm_ready = True

        except Exception as e:
            self.log_to_terminal(f"⚠️ Error attaching Arm: {e}\n")
            return False

        return arm_ready

    def setup_physical_cameras(self, usbipd_out):
        """Attach selected cameras to WSL and discover OpenCV-usable devices."""
        if self.no_cameras_var.get():
            self.detected_cameras = []
            self.log_to_terminal(">> No Cameras Mode Active: Bypassing physical Camera connection.\n")
            return True

        self.log_to_terminal(">> Setting up Cameras...\n")

        try:
            camera_buses = self.get_enabled_camera_buses(usbipd_out)

            if not camera_buses:
                self.log_to_terminal("⚠️ WARNING: No cameras found via usbipd list.\n")
                return True

            selected_camera_buses = list(getattr(self, "last_camera_buses", []) or [])

            if getattr(self, "camera_roles_prompted_before_attach", False):
                camera_buses = [bus for bus in camera_buses if bus in selected_camera_buses]

            self.last_camera_buses = list(camera_buses)

            if not camera_buses:
                self.abort_launch(
                    "❌ No enabled cameras were selected. Server launch aborted. Enable at least one camera role."
                )
                return False

            self.ensure_camera_buses_shared(camera_buses)

            for bus in camera_buses:
                attached_ok, attach_text = self.attach_usbipd_device_to_wsl(
                    bus,
                    "Camera",
                    attempts=3,
                )

                if not attached_ok:
                    short_attach_error = (attach_text.splitlines()[-1] if attach_text.splitlines() else attach_text).strip()
                    self.log_to_terminal(f"⚠️ Failed to attach Camera BUSID {bus}: {short_attach_error}\n")

                    if self.debug_logs_var.get() and attach_text:
                        self.log_to_terminal(f"Debug attach output for Camera BUSID {bus}:\n{attach_text}\n")

            self.log_to_terminal(">> Pausing for 5 seconds to let webcam hardware fully initialize...\n")
            time.sleep(5)

            self.log_to_terminal(">> Unlocking Camera Permissions via Root...\n")
            subprocess.run(
                ["wsl", "-u", "root", "sh", "-c", "chmod 666 /dev/video*"],
                creationflags=subprocess.CREATE_NO_WINDOW,
            )

            self.detected_cameras = self.discover_wsl_cameras()

            if getattr(self, "camera_roles_prompted_before_attach", False):
                self.apply_pending_roles_to_discovered_cameras()

            if not self.detected_cameras:
                self.abort_launch(
                    "❌ Cameras were attached, but none could be opened by OpenCV in WSL. Server launch aborted. Try unplug/replug cameras or use No Cameras Mode."
                )
                return False

            self.log_to_terminal(">> Camera configured: OpenCV-validated MJPG + V4L2 + 640x480.\n")
            return True

        except Exception as e:
            self.log_to_terminal(f"⚠️ Error attaching Camera: {e}\n")
            return True

    def validate_cameras_before_launch(self):
        """Run final camera validation before starting the backend server."""
        if self.detected_cameras and not self.no_cameras_var.get():
            if not self.final_validate_selected_cameras():
                self.abort_launch(
                    "❌ Selected cameras could not be reopened before launch. Server launch aborted. Try launching again or use No Cameras Mode."
                )
                return False

        return True


