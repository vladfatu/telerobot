    def apply_pending_roles_to_discovered_cameras(self):
        """Apply pre-attach role choices to OpenCV-discovered cameras by order."""
        pending = [
            item for item in list(getattr(self, "pending_camera_roles", []) or [])
            if item.get("role") != "disabled"
        ]
        if not pending or not self.detected_cameras:
            return

        assigned = []
        for i, cam in enumerate(self.detected_cameras[:len(pending)]):
            role = pending[i].get("role", "disabled")

            new_cam = copy.deepcopy(cam)
            new_cam["name"] = role

            # Preserve friendlier Windows-side name if available.
            if pending[i].get("usb_name"):
                new_cam["usb_name"] = self.clean_camera_friendly_name(pending[i]["usb_name"])
            elif new_cam.get("usb_name"):
                new_cam["usb_name"] = self.clean_camera_friendly_name(new_cam["usb_name"])

            assigned.append(new_cam)

        if assigned:
            self.detected_cameras = assigned
            self.log_to_terminal("✨ Camera role assignment applied:\n")
            for cam in self.detected_cameras:
                device = cam.get("usb_name", "index {}".format(cam.get("video_index", cam.get("index", "?"))))
                self.log_to_terminal(
                    "   - {}: {} → index {}\n".format(
                        cam["name"],
                        device,
                        cam.get("video_index", cam.get("index", "?")),
                    )
                )


    def stop_wsl_keepalive(self):
        """Stop the temporary WSL keepalive process if it is running."""
        proc = getattr(self, "wsl_keepalive_process", None)
        if proc is None:
            return

        try:
            if proc.poll() is None:
                proc.terminate()
        except Exception:
            pass

        self.wsl_keepalive_process = None

    def keep_wsl_alive_for_usbipd(self):
        """Keep WSL alive only during USB attach.

        This avoids a fixed timer. The launcher starts this temporary process
        after the camera role prompt and before usbipd attach. Once the real
        telerobot server process starts, stop_wsl_keepalive() is called and the
        server itself keeps WSL alive.
        """
        try:
            existing = getattr(self, "wsl_keepalive_process", None)
            if existing is not None and existing.poll() is None:
                return

            self.wsl_keepalive_process = subprocess.Popen(
                ["wsl", "--", "bash", "-lc", "sleep infinity"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )

            time.sleep(1.0)
        except Exception as e:
            self.log_to_terminal(f"⚠️ Warning keeping WSL alive: {e}\n")


