    def calibration_missing(self):
        """Return True when no usable LeRobot calibration JSON file exists."""
        if self.dummy_var.get():
            return False

        check_cmd = (
            "if find ~/.cache/huggingface/lerobot/calibration "
            "-type f -name '*.json' 2>/dev/null | head -1 | grep -q .; then "
            "echo CALIBRATION_OK; "
            "else echo NEEDS_CALIBRATION; fi"
        )

        try:
            res = subprocess.run(
                ["wsl", "--", "bash", "-lc", check_cmd],
                capture_output=True,
                text=True,
                timeout=10,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )

            out = (res.stdout or "") + (res.stderr or "")
            return "NEEDS_CALIBRATION" in out

        except Exception as e:
            self.log_to_terminal(f"âš ï¸ Could not check robot calibration state: {e}\n")
            # Safer to require calibration than to let backend crash on input().
            return True

